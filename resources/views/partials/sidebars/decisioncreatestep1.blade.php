<hr>

<div class="mb-4">
    <strong class="d-block mb-1 text-warning"><i class="bi bi-symmetry-vertical me-1"></i> Binary Cases</strong>
    <p class="fa">
        برای زمان‌هایی که بین انجام دادن یا ندادن یک کار، یا بین دو انتخاب کاملاً متفاوت گیر کرده‌اید
         و هر کدام دلایل مستقل خودشان را دارند.
مثال: فرض کنید می‌خواهید تصمیم بگیرید که آیا مهاجرت کنید یا نه.
شما برای رفتن یک‌سری دلایل دارید (مثل: تجربه زندگی جدید، اقتصاد باثبات، آینده شغلی).
و برای ماندن هم دلایل دیگری دارید (مثل: بودن در کنار خانواده، شهروند درجه یک بودن، فرهنگ و زبان مادری).</p>

    <p>For times when you are stuck between doing or not doing something, or between two completely different choices, each with its own independent reasons.

Example: Suppose you want to decide whether to emigrate or not.
You have some reasons for leaving (e.g., experiencing a new life, a stable economy, better career prospects).
And you have other reasons for staying (e.g., being close to family, feeling like a first-class citizen, native culture and language).</p>
        
</div>

<div>
    <strong class="d-block mb-1 text-warning"><i class="bi bi-ui-radios-grid me-1"></i> Multi Cases</strong>
    <p class="fa">برای زمان‌هایی که می‌خواهید از بین چند گزینه مختلف یکی را انتخاب کنید،
         در حالی که معیارها برای همه گزینه‌ها ثابت است.

مثال: می‌خواهید برای مقطع ارشد بین ۳ دانشگاه (شریف، امیرکبیر و تهران) یکی را انتخاب کنید. معیارهای شما برای همه این دانشگاه‌ها یکسان است: مسافت، رتبه جهانی، وضعیت خوابگاه
 و سطح اساتید.</p>

    <p>For times when you want to choose one out of several different options,
         while the criteria remain the same for all options.

Example: You want to choose between 3 universities (Sharif, Amirkabir, and Tehran) 
for your master's degree. Your criteria for all these universities 
are the same: distance, global ranking, dorm conditions, and the academic level of professors.</p>

    </div>