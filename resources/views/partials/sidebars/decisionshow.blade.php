<hr>

<p>To get an accurate result, you need to add 
    <strong>Factors</strong> (criteria).</p>

<ul class="mb-4 text-sm opacity-75">
    <li>Click <strong>New Factor</strong> to add criteria like Cost, Quality, Distance, etc.</li>
    <li>Weight them from 1 to 5 based on importance.</li>
    <li>Score your options for each factor.</li>
</ul>


<p class="text-info"><i class="bi bi-calculator me-1"></i> 
    Once you have enough factors, hit <strong>Calculate Result</strong>!</p>

<hr>

<p class="fa">در این قسمت میتونین معیار هاتون رو بسازید و وارد کنید</p>

<ul class="mb-4 text-sm opacity-75 fa">
    <li>روی دکمه <strong>New Factor</strong> کلیک کنین و نام معیار رو وارد کنین</li>
    <li>به میزان مهم بودن اون معیار برای خودتون از 1 تا 5 ضریب بدین (5بیشترین است)</li>
    <li>و به هر حالت ، از 1 تا 10 نسبت به اون معیار نمره بدین</li>
</ul>


<p class="text-info fa"><i class="bi bi-calculator me-1"></i> 
    هر موقع تمام معیار ها رو وارد کردید روی دکمه  <strong>Calculate Result</strong>بزنین!</p>